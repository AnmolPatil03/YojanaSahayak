export function translate(
  language: Language,
  key: MessageKey,
  vars: Record<string, string | number> = {},
): string {
  const template = dictionaries[language][key] ?? en[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}

